router.post('/:id/transcribe', async (req, res) => {
  if (!whisperStatus().available) throw new HttpError(503, 'Local Whisper is not installed on the server');
  const meeting = await findOwned(req, { audio: 1, transcription: 1 });
  if (!meeting.audio?.filename) throw new HttpError(400, 'This meeting has no audio to transcribe');
  if (!(await enqueue(meeting._id))) throw new HttpError(409, 'Transcription is already in progress');
  res.status(202).json({ meeting: await findOwned(req) });
});

router.delete('/:id/transcribe', async (req, res) => {
  const meeting = await findOwned(req, { _id: 1 });
  await cancel(meeting._id);
  res.json({ meeting: await findOwned(req) });
});

