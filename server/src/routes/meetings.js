const router = Router();
router.use(requireAuth);

const { ObjectId } = mongoose.Types;

function ownedFilter(req) {
  if (!mongoose.isValidObjectId(req.params.id)) throw new HttpError(404, 'Meeting not found');
  return { _id: req.params.id, user: req.userId };
}

async function findOwned(req, projection) {
  const meeting = await Meeting.findOne(ownedFilter(req), projection);
  if (!meeting) throw new HttpError(404, 'Meeting not found');
  return meeting;
}

const str = (v, max) => String(v ?? '').trim().slice(0, max);

function cleanSegment(raw) {
  const text = str(raw?.text, 10000);
  const startMs = Math.max(0, Math.round(Number(raw?.startMs) || 0));
  const endMs = Math.max(startMs, Math.round(Number(raw?.endMs) || startMs));
  if (!text) return null;
  return {
    _id: new ObjectId(),
    startMs,
    endMs,
    text,
    speaker: str(raw?.speaker, 60) || 'Speaker 1',
    highlighted: Boolean(raw?.highlighted),
  };
}

function cleanTags(tags) {
  if (!Array.isArray(tags)) throw new HttpError(400, 'tags must be an array');
  return [...new Set(tags.map((t) => str(t, 40).toLowerCase()).filter(Boolean))].slice(0, 30);
}

// Transcript edits are locked while Whisper is rewriting it.
async function assertEditable(req) {
  const meeting = await findOwned(req, { 'transcription.status': 1 });
  if (isActive(meeting.transcription?.status)) {
    throw new HttpError(409, 'The transcript is being regenerated by Whisper. Try again when it finishes.');
  }
}

const removeFile = (filename) =>
  filename && fs.promises.unlink(path.join(config.uploadDir, filename)).catch(() => {});

// ---------- list / create ----------

router.get('/', async (req, res) => {
  const q = str(req.query.q, 200);
  const page = clampInt(req.query.page, 1, 10000, 1);
  const limit = clampInt(req.query.limit, 1, 50, 20);

  const match = { user: new ObjectId(req.userId) };
  let previewSource = { $slice: ['$segments', 1] };
  if (q) {
    const rx = new RegExp(escapeRegex(q), 'i');
    match.$or = [{ title: rx }, { notes: rx }, { tags: rx }, { 'segments.text': rx }];
    previewSource = {
      $filter: {
        input: '$segments',
        cond: { $regexMatch: { input: '$$this.text', regex: escapeRegex(q), options: 'i' } },
        limit: 1,
      },
    };
  }

  const [items, total] = await Promise.all([
    Meeting.aggregate([
      { $match: match },
      { $sort: { createdAt: -1 } },
      { $skip: (page - 1) * limit },
      { $limit: limit },
      {
        $project: {
          title: 1,
          status: 1,
          tags: 1,
          language: 1,
          durationMs: 1,
          startedAt: 1,
          createdAt: 1,
          hasAudio: { $cond: [{ $ifNull: ['$audio.filename', false] }, true, false] },
          transcription: { status: 1, progress: 1, source: 1 },
          segmentCount: { $size: '$segments' },
          preview: { $first: previewSource },
        },
      },
      {
        $addFields: {
          preview: { $substrCP: [{ $ifNull: ['$preview.text', ''] }, 0, 240] },
        },
      },
    ]),
    Meeting.countDocuments(match),
  ]);

  res.json({ items, total, page, pages: Math.max(1, Math.ceil(total / limit)) });
});

router.post('/', async (req, res) => {
  const meeting = await Meeting.create({
    user: req.userId,
    title: str(req.body?.title, 200) || `Meeting ${new Date().toLocaleString('en-US')}`,
    language: str(req.body?.language, 20) || 'en-US',
    startedAt: req.body?.startedAt ? new Date(req.body.startedAt) : new Date(),
    tags: req.body?.tags ? cleanTags(req.body.tags) : [],
  });
  res.status(201).json({ meeting });
});

// ---------- single meeting ----------

router.get('/:id', async (req, res) => {
  res.json({ meeting: await findOwned(req) });
});

router.patch('/:id', async (req, res) => {
  const b = req.body || {};
  const $set = {};
  if ('title' in b) {
    $set.title = str(b.title, 200);
    if (!$set.title) throw new HttpError(400, 'Title cannot be empty');
  }
  if ('notes' in b) $set.notes = String(b.notes ?? '').slice(0, 50000);
  if ('tags' in b) $set.tags = cleanTags(b.tags);
  if ('language' in b) $set.language = str(b.language, 20);
  if ('status' in b) {
    if (!['recording', 'completed'].includes(b.status)) throw new HttpError(400, 'Invalid status');
    $set.status = b.status;
  }
  if ('durationMs' in b) $set.durationMs = Math.max(0, Math.round(Number(b.durationMs) || 0));
  if ('endedAt' in b) $set.endedAt = b.endedAt ? new Date(b.endedAt) : null;

  const meeting = await Meeting.findOneAndUpdate(ownedFilter(req), { $set }, { returnDocument: 'after', runValidators: true });
  if (!meeting) throw new HttpError(404, 'Meeting not found');
  res.json({ meeting });
});

router.delete('/:id', async (req, res) => {
  const meeting = await findOwned(req, { audio: 1, tracks: 1 });
  await cancel(meeting._id);
  await meeting.deleteOne();
  removeFile(meeting.audio?.filename);
  removeFile(meeting.tracks?.filename);
  res.status(204).end();
});

// ---------- segments ----------

router.post('/:id/segments', async (req, res) => {
  const raw = req.body?.segments;
  if (!Array.isArray(raw) || raw.length === 0) throw new HttpError(400, 'segments must be a non-empty array');
  if (raw.length > 500) throw new HttpError(400, 'Too many segments in one request (max 500)');
  await assertEditable(req);
  const segments = raw.map(cleanSegment).filter(Boolean);
  if (!segments.length) return res.status(201).json({ segments: [] });

  const result = await Meeting.updateOne(ownedFilter(req), {
    $push: { segments: { $each: segments, $sort: { startMs: 1 } } },
  });
  if (!result.matchedCount) throw new HttpError(404, 'Meeting not found');
  res.status(201).json({ segments });
});

router.patch('/:id/segments/:segId', async (req, res) => {
  if (!mongoose.isValidObjectId(req.params.segId)) throw new HttpError(404, 'Segment not found');
  await assertEditable(req);
  const b = req.body || {};
  const $set = {};
  if ('text' in b) {
    const text = str(b.text, 10000);
    if (!text) throw new HttpError(400, 'Text cannot be empty (delete the segment instead)');
    $set['segments.$.text'] = text;
  }
  if ('speaker' in b) $set['segments.$.speaker'] = str(b.speaker, 60) || 'Speaker 1';
  if ('highlighted' in b) $set['segments.$.highlighted'] = Boolean(b.highlighted);

  const meeting = await Meeting.findOneAndUpdate(
    { ...ownedFilter(req), 'segments._id': req.params.segId },
    { $set },
    { returnDocument: 'after', projection: { segments: { $elemMatch: { _id: req.params.segId } } } },
  );
  if (!meeting) throw new HttpError(404, 'Segment not found');
  res.json({ segment: meeting.segments[0] });
});

router.delete('/:id/segments/:segId', async (req, res) => {
  if (!mongoose.isValidObjectId(req.params.segId)) throw new HttpError(404, 'Segment not found');
  await assertEditable(req);
  const result = await Meeting.updateOne(ownedFilter(req), { $pull: { segments: { _id: req.params.segId } } });
  if (!result.matchedCount) throw new HttpError(404, 'Meeting not found');
  res.status(204).end();
});

router.patch('/:id/speakers', async (req, res) => {
  const from = str(req.body?.from, 60);
  const to = str(req.body?.to, 60);
  if (!from || !to) throw new HttpError(400, 'Both "from" and "to" are required');
  await assertEditable(req);
  const result = await Meeting.updateOne(
    ownedFilter(req),
    { $set: { 'segments.$[s].speaker': to } },
    { arrayFilters: [{ 's.speaker': from }] },
  );
  if (!result.matchedCount) throw new HttpError(404, 'Meeting not found');
  res.json({ meeting: await findOwned(req) });
});

