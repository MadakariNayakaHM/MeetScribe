fs.mkdirSync(config.uploadDir, { recursive: true });

const EXT = {
  'audio/webm': 'webm', 'video/webm': 'webm', 'audio/ogg': 'ogg', 'audio/mp4': 'm4a', 'audio/x-m4a': 'm4a',
  'audio/mpeg': 'mp3', 'audio/wav': 'wav', 'audio/x-wav': 'wav', 'audio/wave': 'wav', 'audio/flac': 'flac',
  'audio/aac': 'aac', 'video/mp4': 'mp4', 'video/quicktime': 'mov',
};
const KNOWN_EXT = new Set(Object.values(EXT));

const upload = multer({
  storage: multer.diskStorage({
    destination: config.uploadDir,
    filename: (req, file, cb) => {
      const fromName = path.extname(file.originalname || '').slice(1).toLowerCase();
      const ext = EXT[file.mimetype.split(';')[0]] || (KNOWN_EXT.has(fromName) ? fromName : 'bin');
      cb(null, `${req.params.id}-${file.fieldname}-${Date.now()}.${ext}`);
    },
  }),
  limits: { fileSize: config.maxUploadMb * 1024 * 1024, files: 2 },
  fileFilter: (_req, file, cb) => {
    const ok = file.mimetype.startsWith('audio/') || file.mimetype.startsWith('video/');
    cb(ok ? null : new HttpError(415, 'Only audio or video files are accepted'), ok);
  },
});

const fileInfo = (f) => ({ filename: f.filename, mimeType: f.mimetype.split(';')[0], size: f.size });

// Fields: "audio" (required, used for playback) and optional "tracks"
// (stereo: left = mic, right = tab audio) used for per-speaker Whisper transcription.
router.post(
  '/:id/audio',
  async (req, _res, next) => {
    req.meeting = await findOwned(req, { audio: 1, tracks: 1, transcription: 1 });
    next();
  },
  upload.fields([{ name: 'audio', maxCount: 1 }, { name: 'tracks', maxCount: 1 }]),
  async (req, res) => {
    const audio = req.files?.audio?.[0];
    const tracks = req.files?.tracks?.[0];
    if (!audio) {
      removeFile(tracks?.filename);
      throw new HttpError(400, 'No audio file received (field name must be "audio")');
    }
    await cancel(req.meeting._id); // a new recording supersedes any running job
    const update = tracks
      ? { $set: { audio: fileInfo(audio), tracks: fileInfo(tracks) } }
      : { $set: { audio: fileInfo(audio) }, $unset: { tracks: 1 } };
    await Meeting.updateOne(ownedFilter(req), update);
    removeFile(req.meeting.audio?.filename);
    removeFile(req.meeting.tracks?.filename);

    const transcribe = req.query.transcribe !== 'false' && whisperStatus().available && whisperStatus().auto;
    if (transcribe) await enqueue(req.meeting._id);
    res.status(201).json({ meeting: await findOwned(req) });
  },
);

